// Settings + Profile: источник данных, язык, симулятор, параметры движка, профиль и роль.
import { useData } from '../features/health/DataProvider'
import { Card, Disclaimer, PageHeader } from '../components/ui'
import { CONFIG, RULESET_VERSION } from '../features/risk-detection/engine'
import { SCENARIOS } from '../features/simulator/simulator'
import { tr, useLang } from '../lib/i18n'

const role = (r: string) =>
  ({ astronaut: tr('Астронавт', 'Astronaut'), medical_officer: tr('Врач миссии', 'Mission medical officer'), admin: tr('Администратор', 'Administrator') })[r] ?? r

export function SettingsPage() {
  const { mode, scenario, live } = useData()
  const { lang, setLang } = useLang()
  return (
    <div className="space-y-5">
      <PageHeader title={tr('Настройки', 'Settings')} subtitle={tr('Источник данных, язык, симулятор и параметры анализа', 'Data source, language, simulator and analysis parameters')} />
      <div className="grid gap-5 lg:grid-cols-2">
        <Card title={tr('Источник данных', 'Data source')}>
          <p className="text-sm">
            {mode === 'supabase'
              ? tr('Подключено к Supabase: авторизация, PostgreSQL с RLS и Realtime.', 'Connected to Supabase: auth, PostgreSQL with RLS and Realtime.')
              : tr(
                  'Автономный демо-режим без регистрации: данные генерирует симулятор прямо в браузере. Подключение Supabase (вход, БД с RLS, Realtime) включается переменной VITE_USE_SUPABASE=true.',
                  'Standalone demo mode, no sign-up: data is generated by a simulator right in the browser. Supabase (sign-in, RLS database, Realtime) is enabled with VITE_USE_SUPABASE=true.',
                )}
          </p>
          <p className="mt-2 text-sm text-ink-dim">
            {tr('Сценарий симулятора', 'Simulator scenario')}: <b className="text-ink">{SCENARIOS[scenario].label}</b> · Live:{' '}
            {live ? tr('включён', 'on') : tr('выключен', 'off')}
          </p>
          <p className="mt-2 text-xs text-ink-mute">
            {tr(
              "Подключение реальных датчиков — следующий этап: записи будут приходить с data_source = 'sensor'.",
              "Connecting real sensors is the next step: records will arrive with data_source = 'sensor'.",
            )}
          </p>
        </Card>
        <Card title={tr('Язык интерфейса', 'Interface language')}>
          <div className="flex gap-2">
            {(
              [
                ['ru', 'Русский'],
                ['en', 'English'],
              ] as const
            ).map(([l, name]) => (
              <button
                key={l}
                onClick={() => setLang(l)}
                aria-pressed={lang === l}
                className={`flex-1 rounded-lg border px-3 py-2 text-sm transition ${lang === l ? 'border-accent bg-nasa-blue/40 text-ink' : 'border-space-600 text-ink-dim hover:bg-space-800'}`}
              >
                {name}
              </button>
            ))}
          </div>
          <p className="mt-2 text-xs text-ink-mute">
            {tr('Выбор сохраняется в этом браузере. Цитаты NASA в ORBIT AI показываются на языке оригинала (английский).', 'Your choice is saved in this browser. NASA quotes in ORBIT AI are shown in the original English.')}
          </p>
        </Card>
        <Card title={`Risk Engine · ${RULESET_VERSION}`} className="lg:col-span-2">
          <pre className="overflow-x-auto rounded-lg bg-space-950 p-3 font-mono text-[11px] text-ink-dim">{JSON.stringify(CONFIG, null, 2)}</pre>
          <p className="mt-2 text-xs text-ink-mute">
            {tr('Демо-параметры чувствительности. Перед реальным использованием их согласовывают со специалистами.', 'Demo sensitivity parameters. They must be agreed with specialists before real use.')}
          </p>
        </Card>
      </div>
      <Disclaimer />
    </div>
  )
}

export function ProfilePage() {
  const { profile, session, mission, mode } = useData()
  return (
    <div className="space-y-5">
      <PageHeader title={tr('Профиль', 'Profile')} />
      <Card>
        <div className="flex items-center gap-4">
          <div className="grid h-14 w-14 place-items-center rounded-full bg-accent/15 text-xl font-semibold text-accent">{profile?.display_name.slice(0, 1) ?? '?'}</div>
          <div>
            <div className="text-lg font-semibold">{profile?.display_name}</div>
            <div className="text-sm text-ink-dim">
              {role(profile?.role ?? 'astronaut')} · {mission?.mission_code ?? tr('без миссии', 'no mission')}
            </div>
            {session?.user.email && <div className="text-xs text-ink-mute">{session.user.email}</div>}
          </div>
        </div>
        <dl className="mt-4 grid gap-2 text-sm sm:grid-cols-2">
          <div>
            <dt className="label-caps">{tr('Роль', 'Role')}</dt>
            <dd>{role(profile?.role ?? 'astronaut')}</dd>
          </div>
          <div>
            <dt className="label-caps">{tr('Режим', 'Mode')}</dt>
            <dd>{mode === 'supabase' ? 'Supabase' : tr('Демо', 'Demo')}</dd>
          </div>
        </dl>
        <p className="mt-4 text-xs text-ink-mute">
          {tr(
            'Права доступа: астронавт видит только свои данные; врач миссии — участников назначенной миссии; администратор управляет конфигурацией без доступа к медицинским данным. Права проверяются политиками RLS в базе данных.',
            'Access: an astronaut sees only their own data; the mission medical officer sees members of the assigned mission; an administrator manages configuration without access to medical data. Access is enforced by RLS policies in the database.',
          )}
        </p>
      </Card>
    </div>
  )
}
